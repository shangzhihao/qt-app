"""Generate tests/quality/cases.toml: toy cases with base pass rates shaped like a real LLM suite.

Run once; the output is committed. About 60 % of cases always pass, 20 % almost
always, 15 % are genuinely uncertain and 5 % (almost) always fail.
"""

import random
from pathlib import Path

TOPICS = [
    "benefits", "deadlines", "documents", "eligibility", "fees",
    "forms", "housing", "income", "residence", "taxes",
]  # fmt: skip
PER_TOPIC = 20


def base_rate(rng: random.Random) -> float:
    r = rng.random()
    if r < 0.60:
        return 1.0
    if r < 0.80:
        return round(rng.uniform(0.95, 0.99), 2)
    if r < 0.95:
        return round(rng.uniform(0.05, 0.95), 2)
    return round(rng.uniform(0.0, 0.02), 2)


def main() -> None:
    rng = random.Random(20261106)
    lines = ["# Generated by scripts/make_cases.py. base_p is the pass rate at full quality.\n"]
    for topic in TOPICS:
        for i in range(1, PER_TOPIC + 1):
            case_id = f"{topic}-{i:02d}"
            lines += [
                "\n[[case]]\n",
                f'id = "{case_id}"\n',
                f'topic = "{topic}"\n',
                f'question = "Question {i} about {topic}?"\n',
                f'expected = "answer-{case_id}"\n',
                f"base_p = {base_rate(rng)}\n",
            ]
    out = Path(__file__).resolve().parents[1] / "tests" / "quality" / "cases.toml"
    out.write_text("".join(lines))
    print(f"wrote {len(TOPICS) * PER_TOPIC} cases to {out}")


if __name__ == "__main__":
    main()
